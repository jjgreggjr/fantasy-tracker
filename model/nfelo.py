"""greerreNFL public CSVs (nfelo units, nfelo elo, 538-style QB elo, WEPA, market lines, film margins) -> gated raw tables.

The repos carry no LICENSE: the CSVs are cached under model/cache/nfelo/ (git-ignored) and never committed. Every run asks
the server whether a file changed (If-None-Match / If-Modified-Since: a 304 costs nothing) unless NFELO_OFFLINE=1; a network
failure falls back to the cached copy, and with no cached copy the table is simply absent (the `nfelo` columns are NaN), like
the adp / college tables. Opt-in only: `load_store(nfelo=True)` (the matrix builder) adds these tables; the serving store does not.

known_at, per table (the leakage decisions):

  nf_units, nf_elo, nf_qb   pre-game ratings, one row per (season, week, team). They are computed from earlier games only, but
                            the CSV is republished weekly, so a row is stamped known at THAT WEEK'S FIRST KICKOFF - 1h
                            (`RATING_LEAD`). Checked against the nfelounits git history: the 2026 week-6 rows were committed
                            2026-10-13 05:22 PT, two days before week 6's first kickoff, so the stamp is later than reality.
                            Only `_pre` columns are loaded (`_post` is the game's own result). Two documented caveats: the whole
                            history is regenerated by today's model (a Feb-2026 refactor), and a past game's QB is the ACTUAL
                            starter (nf_qb, elo.qb_adj), which is normally but not always known before Thursday.
  nf_wepa, nf_film          one row per (team, game), the game's own WEPA / film margin: stamped at the game's kickoff like
                            every result table, so features read them at kickoff - RESULT_LAG and only earlier games enter.
  nf_lines                  long form, one row per (game, kind, value). A value carries its own scrape timestamp
                            (`*_timestamp`, 2024+). The legacy rows (<= 2023) have no timestamp: their open and last lines are
                            stamped kickoff - 60 min, the same rule as nflverse's closing lines (LINES_CLOSE_LEAD). A `last`
                            line scraped at or after kickoff is excluded by the gate, so the feature falls back to the open.
  coaches.csv               NOT loaded: career aggregates through today (wins, ATS, playoff record) are not point-in-time,
                            so any value would leak later seasons into earlier rows.

Team codes: these files use LAR and OAK (for the Raiders in every season); the store uses nflverse codes (LA; LV from 2020,
OAK before). `team_code` / `game_id` translate; an unmapped game is dropped and counted.
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import requests

from model import point_in_time as pit
from model.point_in_time import KNOWN_AT, RawTable

NFELO_DIR = pit.CACHE_DIR / "nfelo"
_RAW = "https://raw.githubusercontent.com/greerreNFL"
SOURCES = {
    "units.csv": f"{_RAW}/nfelounits/refs/heads/main/Output/units.csv",
    "elo.csv": f"{_RAW}/nfelounits/refs/heads/main/Output/elo.csv",
    "qb_elos.csv": f"{_RAW}/nfeloqb/main/qb_elos.csv",
    "wepa_by_game_pit.csv": f"{_RAW}/wepa/main/data/wepa_by_game_pit.csv",
    "lines.csv": f"{_RAW}/nfelomarket_data/main/Data/lines.csv",
    "film_margins.csv": f"{_RAW}/filmmargin/main/film_margins.csv",
}
RATING_LEAD = pd.Timedelta(hours=1)          # weekly ratings: known at the week's first kickoff - 1h
UNIT_COLS = ["pass_off_value_pre", "rush_off_value_pre", "pass_def_value_pre", "rush_def_value_pre",
             "off_value_pre", "def_value_pre", "total_value_pre"]
LINE_KINDS = ("spread_open", "spread_last", "total_open", "total_last", "tickets")


# --------------------------------------------------------------------------- team codes
def team_code(code: str, season: int) -> str:
    """nfelo / nflfastR-style code -> the store's nflverse code for that season."""
    if code == "LAR" or code == "STL" and season >= 2016:
        return "LA"
    if code == "OAK" and season >= 2020:
        return "LV"
    if code == "SD" and season >= 2017:
        return "LAC"
    return code


def game_id(gid: str) -> str | None:
    """'2026_06_BUF_OAK' -> '2026_06_BUF_LV'. None when the id does not parse."""
    parts = str(gid).split("_")
    if len(parts) != 4 or not parts[0].isdigit():
        return None
    s = int(parts[0])
    return f"{parts[0]}_{parts[1]}_{team_code(parts[2], s)}_{team_code(parts[3], s)}"


# --------------------------------------------------------------------------- fetch
def fetch(name: str, *, cache_dir: Path | None = None, session=requests) -> Path | None:
    """Conditional download of one source CSV. Returns the cached path, or None when there is no copy at all."""
    cache_dir = cache_dir or NFELO_DIR
    dest = cache_dir / name
    meta_path = dest.with_suffix(dest.suffix + ".meta.json")
    have = dest.exists() and dest.stat().st_size > 0
    if os.environ.get("NFELO_OFFLINE") == "1":
        return dest if have else None
    headers = {}
    if have and meta_path.exists():
        meta = json.loads(meta_path.read_text())
        if meta.get("etag"):
            headers["If-None-Match"] = meta["etag"]
        if meta.get("last_modified"):
            headers["If-Modified-Since"] = meta["last_modified"]
    try:
        r = session.get(SOURCES[name], headers=headers, timeout=120)
        if r.status_code == 304 and have:
            return dest
        r.raise_for_status()
    except requests.RequestException as e:
        print(f"nfelo: could not refresh {name} ({e}); {'using the cached copy' if have else 'no cached copy, table skipped'}",
              file=sys.stderr, flush=True)
        return dest if have else None
    cache_dir.mkdir(parents=True, exist_ok=True)
    tmp = dest.with_suffix(dest.suffix + ".part")
    tmp.write_bytes(r.content)
    tmp.replace(dest)
    meta_path.write_text(json.dumps({"etag": r.headers.get("ETag"), "last_modified": r.headers.get("Last-Modified"),
                                     "fetched_at": pd.Timestamp.now(tz="UTC").isoformat(), "url": SOURCES[name]}))
    return dest


# --------------------------------------------------------------------------- frame builders (pure; tests call these)
def week_first_kickoffs(games: pd.DataFrame) -> pd.Series:
    """{(season, week): first kickoff of the week} over REG games (the rating tables are REG only)."""
    g = games[games["game_type"] == "REG"]
    return g.groupby(["season", "week"])["kickoff"].min()


def _stamp_weekly(df: pd.DataFrame, first_ko: pd.Series) -> tuple[pd.DataFrame, int]:
    k = pd.Series(list(zip(df["season"].astype(int), df["week"].astype(int))), index=df.index).map(first_ko)
    out = df[k.notna()].copy()
    out[KNOWN_AT] = pit._ns_utc(k[k.notna()] - RATING_LEAD)
    return out.reset_index(drop=True), int(k.isna().sum())


def units_frame(raw: pd.DataFrame, first_ko: pd.Series) -> tuple[pd.DataFrame, dict]:
    df = raw[["season", "week", "team", *UNIT_COLS]].copy()           # _post columns are the game's own result: never loaded
    df["team"] = [team_code(c, s) for c, s in zip(df["team"], df["season"])]
    df, n = _stamp_weekly(df, first_ko)
    return df, {"week_not_in_schedule": n}


def elo_frame(raw: pd.DataFrame, first_ko: pd.Series) -> tuple[pd.DataFrame, dict]:
    df = raw[["season", "week", "team", "elo", "qb_adj"]].copy()
    df["team"] = [team_code(c, s) for c, s in zip(df["team"], df["season"])]
    df, n = _stamp_weekly(df, first_ko)
    return df, {"week_not_in_schedule": n}


def qb_frame(raw: pd.DataFrame, first_ko: pd.Series, kickoffs: pd.Series) -> tuple[pd.DataFrame, dict]:
    """Two rows per REG game (team1 = home, team2 = away), each with that team's starting QB's pre-game value."""
    q = raw[(raw["game_type"] == "REG") & raw["week"].notna() & raw["game_id"].notna()].copy()
    q["gid"] = q["game_id"].map(game_id)
    sides = []
    for a, b in (("1", "2"), ("2", "1")):
        s = pd.DataFrame({"season": q["season"].astype(int), "week": q["week"].astype(int), "game_id": q["gid"],
                          "team": [team_code(c, y) for c, y in zip(q[f"team{a}"], q["season"])],
                          "qb": q[f"qb{a}"], "qb_value_pre": q[f"qb{a}_value_pre"]})
        sides.append(s)
    df = pd.concat(sides, ignore_index=True)
    known = df["game_id"].isin(kickoffs.index)
    n_game = int((~known).sum())
    df, n_week = _stamp_weekly(df[known], first_ko)
    return df, {"game_not_in_schedule": n_game, "week_not_in_schedule": n_week}


def per_game_frame(raw: pd.DataFrame, cols: list[str], kickoffs: pd.Series) -> tuple[pd.DataFrame, dict]:
    """A (team, game) result table: stamped at the game's kickoff."""
    df = raw[["game_id", "season", "team", *cols]].copy()
    df["game_id"] = df["game_id"].map(game_id)
    df["team"] = [team_code(c, s) for c, s in zip(df["team"], df["season"])]
    ko = df["game_id"].map(kickoffs)
    n = int(ko.isna().sum())
    df = df[ko.notna()].copy()
    df[KNOWN_AT] = pit._ns_utc(ko[ko.notna()])
    return df.reset_index(drop=True), {"game_not_in_schedule": n}


def _ts(s: pd.Series) -> pd.Series:
    return pd.to_datetime(s, utc=True, errors="coerce", format="mixed")


def lines_frame(raw: pd.DataFrame, kickoffs: pd.Series) -> tuple[pd.DataFrame, dict]:
    """Long form [game_id, season, week, home_team, kind, value, timestamped, known_at]. `value` is from the HOME team's view
    (spreads: negative = home favoured; tickets: share of spread tickets on the home side)."""
    l = raw.copy()
    l["gid"] = l["game_id"].map(game_id)
    ko = l["gid"].map(kickoffs)
    n_game = int(ko.isna().sum())
    l, ko = l[ko.notna()], ko[ko.notna()]
    legacy = ko - pit.LINES_CLOSE_LEAD
    spec = {"spread_open": ("home_spread_open", "home_spread_open_timestamp"),
            "spread_last": ("home_spread_last", "home_spread_last_timestamp"),
            "total_open": ("total_line_open", "total_line_open_timestamp"),
            "total_last": ("total_line_last", "total_line_last_timestamp"),
            "tickets": ("home_spread_tickets_pct", "home_spread_pct_timestamp")}
    parts = []
    for kind, (vcol, tcol) in spec.items():
        v = pd.to_numeric(l[vcol], errors="coerce")
        ts = _ts(l[tcol]) if tcol in l.columns else pd.Series(pd.NaT, index=l.index, dtype="datetime64[ns, UTC]")
        has_ts = ts.notna()
        part = pd.DataFrame({"game_id": l["gid"], "season": l["season"].astype(int), "week": l["week"].astype(int),
                             "home_team": [team_code(c, s) for c, s in zip(l["home_team"], l["season"])],
                             "kind": kind, "value": v, "timestamped": has_ts,
                             KNOWN_AT: ts.where(has_ts, legacy)})
        parts.append(part[v.notna()])
    df = pd.concat(parts, ignore_index=True)
    df[KNOWN_AT] = pit._ns_utc(df[KNOWN_AT])
    df = df.sort_values([KNOWN_AT, "game_id", "kind"], kind="mergesort").reset_index(drop=True)
    return df, {"game_not_in_schedule": n_game}


# --------------------------------------------------------------------------- the tables
def load_nfelo_tables(seasons, *, cache_dir: Path | None = None) -> list[RawTable]:
    """Every nfelo table whose CSV is available (fetched or cached), restricted to `seasons`."""
    seasons = set(int(s) for s in seasons)
    games = pit._games()
    first_ko, kickoffs = week_first_kickoffs(games), games.set_index("game_id")["kickoff"]
    rule_w = "the week's first REG kickoff - 1h (pre-game rating; weekly republication, verified 2026)"
    rule_g = "game kickoff (the game's own value; read at kickoff - RESULT_LAG)"
    out: list[RawTable] = []

    def read(name: str) -> pd.DataFrame | None:
        p = fetch(name, cache_dir=cache_dir)
        if p is None:
            return None
        d = pd.read_csv(p, low_memory=False)
        return d[d["season"].isin(seasons)]

    if (d := read("units.csv")) is not None:
        df, dropped = units_frame(d, first_ko)
        out.append(RawTable("nf_units", df, rule_w, dropped=dropped))
    if (d := read("elo.csv")) is not None:
        df, dropped = elo_frame(d, first_ko)
        out.append(RawTable("nf_elo", df, rule_w, proxy="qb_adj reflects the ACTUAL starter of a past game", dropped=dropped))
    if (d := read("qb_elos.csv")) is not None:
        df, dropped = qb_frame(d, first_ko, kickoffs)
        out.append(RawTable("nf_qb", df, rule_w, proxy="the starter of a past game is the ACTUAL starter", dropped=dropped))
    if (d := read("wepa_by_game_pit.csv")) is not None:
        df, dropped = per_game_frame(d, ["opponent", "wepa_net"], kickoffs)
        out.append(RawTable("nf_wepa", df, rule_g, dropped=dropped))
    if (d := read("film_margins.csv")) is not None:
        df, dropped = per_game_frame(d, ["week", "film_margin_predictive"], kickoffs)
        out.append(RawTable("nf_film", df, rule_g, dropped=dropped))
    if (d := read("lines.csv")) is not None:
        df, dropped = lines_frame(d, kickoffs)
        out.append(RawTable("nf_lines", df, "the value's own scrape timestamp (2024+); legacy rows kickoff - 60min",
                            dropped=dropped))
    return out
